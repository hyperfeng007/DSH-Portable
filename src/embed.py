#!/usr/bin/env python3
"""Turn the launcher scripts into C string constants (scripts.h).

Bytes are emitted as octal escapes so UTF-8 text survives untouched and no
\\x-escape can swallow the following hex-looking characters."""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
FILES = [
    ("SCRIPT_START_DSH_PS1",    "Start-DSH.ps1"),
    ("SCRIPT_INSTALL_DSH_BAT",  "Install-DSH.bat"),
    ("SCRIPT_UPDATE_DSH_BAT",   "Update-DSH.bat"),
    ("SCRIPT_DSH_TERMINAL_BAT", "DSH-Terminal.bat"),
    ("SCRIPT_STOP_DSH_BAT",     "Stop-DSH.bat"),
]

def c_literal_lines(data: bytes):
    out = []
    for raw in data.replace(b"\r\n", b"\n").split(b"\n"):
        seg = []
        for ch in raw:
            if ch == 0x5C:            seg.append("\\\\")
            elif ch == 0x22:          seg.append('\\"')
            elif 0x20 <= ch < 0x7F:   seg.append(chr(ch))
            elif ch == 0x09:          seg.append("\\t")
            else:                     seg.append("\\%03o" % ch)
        out.append('"' + "".join(seg) + '\\n"')
    # drop the empty literal produced by a trailing newline
    if out and out[-1] == '"\\n"':
        out.pop()
    return out

BINARIES = [
    ("BIN_CTRLC_EXE", "ctrlc.exe"),
]

def main():
    lines = ["/* generated by embed.py - do not edit, edit the scripts instead */", ""]
    for name, fn in FILES:
        data = open(os.path.join(HERE, fn), "rb").read()
        if data.startswith(b"\xef\xbb\xbf"):
            data = data[3:]
        lines.append("static const char %s[] =" % name)
        lines.extend("    " + l for l in c_literal_lines(data))
        lines.append("    ;")
        lines.append("")
    for name, fn in BINARIES:
        data = open(os.path.join(HERE, fn), "rb").read()
        lines.append("static const unsigned int %s_LEN = %d;" % (name, len(data)))
        lines.append("static const unsigned char %s[] = {" % name)
        for i in range(0, len(data), 24):
            lines.append("    " + ",".join("%d" % b for b in data[i:i+24]) + ",")
        lines.append("};")
        lines.append("")
    open(os.path.join(HERE, "scripts.h"), "w", encoding="ascii").write("\n".join(lines))
    print("scripts.h written (%d scripts, %d binaries)" % (len(FILES), len(BINARIES)))

if __name__ == "__main__":
    main()
